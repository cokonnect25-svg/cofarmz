const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const data = new Map();
global.window = {};
global.localStorage = { setItem: (k,v) => data.set(k,v), getItem: k => data.get(k), removeItem: k => data.delete(k) };
const mod = new Module('mobile-credential-test', module);
mod._compile(ts.transpileModule(fs.readFileSync('lib/mobile-credential.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, 'mobile-credential-test');
const { storeMobileCredential, getMobileCredential, clearMobileCredential } = mod.exports;
storeMobileCredential('signed-token');
assert.equal(getMobileCredential(), 'signed-token');
clearMobileCredential();
assert.equal(getMobileCredential(), null);
storeMobileCredential('previous-account');
storeMobileCredential();
assert.equal(getMobileCredential(), null);
storeMobileCredential('expired');
const key = [...data.keys()][0];
data.set(key, JSON.stringify({ token: 'expired', expiresAt: Date.now() - 1 }));
assert.equal(getMobileCredential(), null);
assert.equal(data.size, 0);
data.set(key, 'broken-json');
assert.equal(getMobileCredential(), null);
console.log('PASS: mobile credential persistence, logout, account replacement, expiration and malformed storage');
