const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const compiled = new Module('fpo-profile-test', module);
compiled.require = name => name === './fpo-error' ? { FpoError: class extends Error {} } : require(name);
compiled._compile(ts.transpileModule(fs.readFileSync('lib/fpo-profile.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText,'fpo-profile-test');
const { validateFpoContact, fpoMapUrl } = compiled.exports;
assert.equal(fpoMapUrl({}),null);
assert.equal(fpoMapUrl({office_address:'   '}),null);
assert.equal(fpoMapUrl({latitude:0,longitude:0}),'https://www.google.com/maps/search/?api=1&query=0%2C0');
assert.equal(fpoMapUrl({latitude:NaN,longitude:12}),null);
assert.equal(fpoMapUrl({latitude:91,longitude:12}),null);
assert.equal(fpoMapUrl({latitude:12}),null);
assert(fpoMapUrl({office_address:'Office & Market Road'}).endsWith('Office%20%26%20Market%20Road'));
assert(fpoMapUrl({latitude:12,longitude:78,office_address:'Office'}).endsWith('12%2C78'));
assert.deepEqual(validateFpoContact({}),{contact_phone:null,office_address:null,latitude:null,longitude:null});
assert.equal(validateFpoContact({contact_phone:' +91 98765 43210 '}).contact_phone,'+91 98765 43210');
for (const input of [{latitude:12},{longitude:12},{latitude:91,longitude:0},{latitude:0,longitude:181},{latitude:NaN,longitude:0},{latitude:'12',longitude:78},{contact_phone:'javascript:alert(1)'},{contact_phone:'-------'},{office_address:'x'.repeat(501)}]) assert.throws(()=>validateFpoContact(input));
console.log('PASS: absent locations, zero coordinates, address encoding, coordinate priority, phone and location validation');
